/**
 * Official UAP records published by the U.S. Department of War.
 *
 * The registry in the Alien monitor showed the `uap_sightings` table and a
 * frozen NUFORC mirror, so the agency releases at https://www.war.gov/ufo/ —
 * the files AARO and the Department of War have been publishing since May 2026
 * — never reached the anomaly feed. This module is the missing source.
 *
 * Provenance is explicit: every record keeps the page it came from, the agency
 * that released it and the release date, and the card links to the document.
 * The release date is what sorts the feed, because a 1957 report published last
 * week is news today; the incident date travels in its own field so the two are
 * never confused.
 *
 * The snapshot in `public/data/war-gov-uap.json` is generated by
 * `npm run sync:war-gov` (scripts/sync-war-gov.mjs): war.gov answers 403 to
 * non-browser clients and the CSV has no CORS header, so the browser cannot
 * read the index directly.
 */

export const WAR_GOV_SOURCE = {
  label: "war.gov/ufo",
  pageUrl: "https://www.war.gov/ufo/",
} as const;

interface ReleaseEntry {
  date: string;
  count: number;
}

interface AgencyEntry {
  name: string;
  count: number;
}

interface WarGovRecord {
  id: string;
  release: string;
  title: string;
  type: string;
  agency: string | null;
  incident: string | null;
  location: string | null;
  featured: boolean;
  blurb: string | null;
  url: string;
}

export interface WarGovSnapshot {
  generatedAt: string;
  total: number;
  latestRelease: string | null;
  earliestRelease: string | null;
  releases: ReleaseEntry[];
  agencies: AgencyEntry[];
  records: WarGovRecord[];
}

/** Shown next to the registry so the release window is always visible. */
export interface WarGovMeta {
  total: number;
  latestRelease: string | null;
  releases: ReleaseEntry[];
  generatedAt: string;
  /** Agencies that published at least one record, newest snapshot first. */
  agencies: number;
}

/** One row of the anomaly registry, as the Alien monitor renders it. */
export interface AnomalyRecord {
  id: string;
  location: string;
  date_reported: string | null;
  type: string | null;
  severity: string | null;
  description: string | null;
  source: string | null;
  source_url: string | null;
  lat: number | null;
  lon: number | null;
  /** Document heading; only the official releases carry one. */
  title?: string | null;
}

/**
 * An incident the agency did not place. The card still has to say something, so
 * it says exactly that instead of inventing a country.
 */
const UNDISCLOSED_LOCATION = "Ubicación no declarada";

const clean = (value: string | null | undefined) => (value ?? "").replace(/\s+/g, " ").trim();

/**
 * Pure mapper, exported so the shape can be tested from a fixture without a
 * network call. `severity` is `official`: this feed is not a witness report and
 * calling a 1957 intelligence memo a "confirmed UAP" would be a claim nobody
 * made.
 */
export function mapWarGovRecords(snapshot: WarGovSnapshot | null): AnomalyRecord[] {
  if (!snapshot?.records?.length) return [];

  return snapshot.records.map((record) => {
    const agency = clean(record.agency);
    const incident = clean(record.incident);
    const where = clean(record.location) || UNDISCLOSED_LOCATION;
    const blurb = clean(record.blurb);
    const description = [blurb, incident ? `Incidente: ${incident}` : ""]
      .filter(Boolean)
      .join(" · ")
      .slice(0, 420);

    return {
      id: record.id,
      location: where,
      date_reported: record.release || null,
      type: record.type || "Registro oficial",
      severity: "official",
      description: description || clean(record.title) || null,
      source: agency ? `${WAR_GOV_SOURCE.label} · ${agency}` : WAR_GOV_SOURCE.label,
      source_url: record.url || WAR_GOV_SOURCE.pageUrl,
      lat: null,
      lon: null,
      title: clean(record.title) || null,
    };
  });
}

let snapshotPromise: Promise<WarGovSnapshot | null> | null = null;

/** Same-origin asset, loaded once per session; a failure just drops the feed. */
function loadSnapshot(): Promise<WarGovSnapshot | null> {
  if (!snapshotPromise) {
    snapshotPromise = fetch("/data/war-gov-uap.json", { signal: AbortSignal.timeout(8000) })
      .then((response) => (response.ok ? (response.json() as Promise<WarGovSnapshot>) : null))
      .catch(() => null);
  }
  return snapshotPromise;
}

/**
 * Every published record, newest release first. Resolves to `[]` on any
 * failure: the registry keeps the other feeds instead of showing an error for
 * one source.
 */
export async function fetchWarGovRecords(): Promise<AnomalyRecord[]> {
  return mapWarGovRecords(await loadSnapshot());
}

/** Release window and counts, for the provenance line of the registry. */
export async function fetchWarGovMeta(): Promise<WarGovMeta | null> {
  const snapshot = await loadSnapshot();
  if (!snapshot) return null;
  return {
    total: snapshot.total,
    latestRelease: snapshot.latestRelease,
    releases: snapshot.releases ?? [],
    generatedAt: snapshot.generatedAt,
    agencies: snapshot.agencies?.length ?? 0,
  };
}
