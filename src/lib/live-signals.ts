/**
 * Curated live signals for the anomaly monitor.
 *
 * Every entry was checked from the build machine before being listed:
 *  - `youtube.com/oembed` returns 200 → the video exists AND its owner allows
 *    being embedded (this is what made the previous list fail: 5 of its 6
 *    cameras now answer 404/403).
 *  - `i.ytimg.com/vi/<id>/hqdefault.jpg` returns 200 → the poster is real.
 *  - `"isLiveNow"` was read from the watch page → `liveAtBuild`.
 *
 * Live status changes constantly, so the player also detects failures at
 * runtime and offers the official page instead of showing a broken box.
 *
 * Las cámaras de fauna se localizaron recorriendo los canales oficiales
 * (`youtube.com/@canal/live`) y la búsqueda filtrada por "en directo", y cada
 * candidata pasó las tres comprobaciones antes de entrar en la lista. Las de
 * jardines y biosferas (25 oct 2026) siguieron el mismo camino: búsqueda
 * filtrada por "en directo", descartando los bucles de relajación que se hacen
 * pasar por cámara. La verificación es una foto de ese día: una cámara
 * estacional (osos, pingüinos, otoño, nieve) puede dejar de emitir sin cambiar
 * este archivo.
 *
 * Por eso `npm run verify:live` (job semanal `verify-live.yml`) repite las tres
 * comprobaciones y deja el resultado en `live-status.generated.ts`: la pestaña
 * Alien marca «sin emisión» lo que ya no emite, sin tocar esta lista.
 */

