/**
 * Sondas de las cámaras en directo, sin dependencias y con `fetch` inyectable.
 *
 * Vive aparte del script que las ejecuta para poder probarlo con respuestas
 * simuladas: el estado de una cámara depende de tres peticiones distintas a
 * YouTube y probar eso contra la red real sería lento y frágil.
 *
 * Criterios (los mismos con los que se curó la lista):
 *  - oembed 200  → el vídeo existe y su dueño permite incrustarlo.
 *  - póster 200  → `hqdefault` es una imagen real, no un 404.
 *  - `"isLiveNow":true` o un `hlsManifestUrl` en la página de visionado → emite.
 */

const USER_AGENT =
  "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";

export const oembedUrl = (videoId) =>
  `https://www.youtube.com/oembed?url=${encodeURIComponent(`https://www.youtube.com/watch?v=${videoId}`)}&format=json`;

export const watchUrl = (videoId) => `https://www.youtube.com/watch?v=${videoId}`;

export const thumbUrl = (videoId) => `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`;

/** Estado de una sonda; `null` = no se pudo determinar (red, 429, captcha). */
export const LIVE = "live";
export const OFFLINE = "offline";
export const UNKNOWN = "unknown";

const RETRY_DELAYS_MS = [1_500, 5_000];

/**
 * YouTube responde 429 cuando se le piden muchas páginas seguidas. Con ~140
 * cámaras es lo normal, así que cada petición reintenta con espera creciente
 * antes de dejar el resultado en «no se pudo comprobar».
 */
async function request(fetchImpl, url, { method = "GET", timeoutMs = 15_000 } = {}) {
  for (let attempt = 0; ; attempt++) {
    const res = await fetchImpl(url, {
      method,
      redirect: "follow",
      headers: { "user-agent": USER_AGENT, accept: "*/*", "accept-language": "es-ES,es;q=0.9,en;q=0.8" },
      signal: AbortSignal.timeout(timeoutMs),
    });
    const retryable = res.status === 429 || res.status === 503;
    if (!retryable || attempt >= RETRY_DELAYS_MS.length) return res;
    await new Promise((done) => setTimeout(done, RETRY_DELAYS_MS[attempt]));
  }
}

/** Sonda una cámara. Nunca lanza: los fallos se devuelven dentro del resultado. */
export async function probeSignal(signal, deps = {}) {
  const { fetchImpl = fetch, timeoutMs = 15_000 } = deps;
  const result = {
    id: signal.id,
    embeddable: null,
    thumbnail: null,
    live: null,
    http: { oembed: null, thumb: null, watch: null },
    note: null,
  };

  try {
    const res = await request(fetchImpl, oembedUrl(signal.videoId), { timeoutMs });
    result.http.oembed = res.status;
    result.embeddable = res.ok;
  } catch (error) {
    result.note = `oembed: ${error instanceof Error ? error.message : String(error)}`;
  }

  try {
    let res = await request(fetchImpl, thumbUrl(signal.videoId), { method: "HEAD", timeoutMs });
    // Algunos CDN rechazan HEAD; se reintenta con GET antes de darlo por roto.
    if (res.status === 405 || res.status === 501) {
      res = await request(fetchImpl, thumbUrl(signal.videoId), { timeoutMs });
    }
    result.http.thumb = res.status;
    result.thumbnail = res.ok;
  } catch {
    result.thumbnail = null;
  }

  try {
    const res = await request(fetchImpl, watchUrl(signal.videoId), { timeoutMs });
    result.http.watch = res.status;
    if (res.ok) {
      const html = await res.text();
      // La página de un directo activo incluye el manifiesto HLS; la de un vídeo
      // terminado, no. `isLiveNow` es la marca explícita del reproductor.
      result.live = /"isLiveNow":true/.test(html) || /"hlsManifestUrl"/.test(html);
    }
  } catch {
    result.live = null;
  }

  return result;
}

/**
 * Traduce la sonda a algo que la app pueda usar.
 * - offline: existe y se puede incrustar, pero no está emitiendo.
 * - unknown: no se pudo comprobar; se deja el estado anterior en la app.
 */
export function classifyProbe(probe) {
  if (probe.live === true) return LIVE;
  if (probe.live === false && probe.embeddable === true) return OFFLINE;
  return UNKNOWN;
}

/**
 * Evita machacar la lista buena cuando la máquina que ejecuta el script no tiene
 * salida a YouTube (CI bloqueada, DNS roto): si casi todo es «unknown», es un
 * fallo del entorno, no 60 cámaras apagadas a la vez.
 */
export function looksLikeNetworkFailure(results, threshold = 0.6) {
  if (results.length === 0) return false;
  const unknown = results.filter((result) => classifyProbe(result) === UNKNOWN).length;
  return unknown / results.length >= threshold;
}

/** Cuerpo del módulo TypeScript que consume la app. */
export function renderStatusModule(checkedOn, checkedAtIso, results) {
  const lines = [
    "// Generated by `npm run verify:live` — do not edit by hand.",
    "// Weekly re-check of every camera in `live-signals.ts`: oembed, poster and",
    "// live state read from the watch page. `live: null` means the probe could not",
    "// determine it (network, 429), and the app then keeps the build-time flag.",
    "",
    `export const LIVE_STATUS_CHECKED_ON = ${JSON.stringify(checkedOn)};`,
    "",
    "export interface LiveSignalStatus {",
    "  live: boolean | null;",
    "  embeddable: boolean | null;",
    "  checkedAt: string;",
    "}",
    "",
    "export const LIVE_STATUS: Record<string, LiveSignalStatus> = {",
  ];

  for (const result of results) {
    lines.push(
      `  ${JSON.stringify(result.id)}: { live: ${result.live === null ? "null" : String(result.live)}, ` +
        `embeddable: ${result.embeddable === null ? "null" : String(result.embeddable)}, ` +
        `checkedAt: ${JSON.stringify(checkedAtIso)} },`,
    );
  }

  lines.push("};", "");
  return lines.join("\n");
}
